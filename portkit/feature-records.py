#!/usr/bin/env python3
"""PortKit per-feature records (Build 15, P7-03 feature registry fields, P7-09 per-feature record).

One section per feature, from the registry (.github/plus/features.json), PortKit's levels
(portkit/compatibility.json) and policy (portkit/policy.json), and the upstream base commit:
ID, level and verification, supported versions, source sets, files split into Nuvio files Plus
changes (integration points) and Plus's own files, dependencies, data formats, tests,
non-transferable parts, limits and known conflicts. Nothing here is typed by hand per feature, so
the records cannot drift from the registry.

  feature-records.py            print the records
  feature-records.py --write    write portkit/reports/feature-records.md
  feature-records.py --check    exit 1 if that file is out of date (run by the script tests)
"""
import fnmatch
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "portkit/reports/feature-records.md"
TOP_LEVEL = ("composeApp/", "androidApp/", "iosApp/", ".github/", "docs/", "gradle/", "signing/")


def resolve(path):
    return path if path.startswith(TOP_LEVEL) or "/" not in path else "composeApp/src/" + path


def in_base(base, path):
    return subprocess.run(["git", "-C", str(ROOT), "cat-file", "-e", f"{base}:{path}"],
                          capture_output=True).returncode == 0


def source_set(path):
    parts = path.split("/")
    if parts[:2] == ["composeApp", "src"] and len(parts) > 2:
        return f"composeApp {parts[2]}"
    if parts[:2] == ["androidApp", "src"] and len(parts) > 2:
        return f"androidApp {parts[2]}"
    return parts[0]


def records():
    registry = json.loads((ROOT / ".github/plus/features.json").read_text())
    overlay = json.loads((ROOT / "portkit/compatibility.json").read_text())
    policy = json.loads((ROOT / "portkit/policy.json").read_text())
    base = overlay["upstream_base"]
    if subprocess.run(["git", "-C", str(ROOT), "cat-file", "-e", f"{base['commit']}^{{commit}}"],
                      capture_output=True).returncode != 0:
        raise SystemExit(f"upstream base {base['commit'][:8]} is not fetched: git fetch it first")
    shared = overlay.get("shared_files", {})
    lines = ["# PortKit per-feature records", "",
             f"Generated by `portkit/feature-records.py` from `.github/plus/features.json`, `portkit/compatibility.json` "
             f"and `portkit/policy.json`, against Nuvio {base['version']} (`{base['commit'][:8]}`). "
             "Integration points are the Nuvio files a feature changes (they exist upstream); Plus files are its own.", ""]
    for feature in registry["features"]:
        fid = feature["id"]
        entry = overlay["features"][fid]
        files = [resolve(p) for p in feature.get("files", [])]
        tests = [resolve(p) for p in feature.get("test_files", [])]
        removed = [resolve(p) for p in feature.get("removed_files", [])]
        nuvio = [p for p in files if in_base(base["commit"], p)]
        own = [p for p in files if p not in nuvio]
        evidence = entry.get("evidence") or {}
        if entry.get("verified"):
            versions = (f"Nuvio {base['version']} and a fork of it (fixtures/fork-a.patch): transfer, build and tests "
                        f"passed ([run]({evidence['run']}) on `{evidence['commit'][:8]}`)")
        else:
            versions = f"Planned against Nuvio {base['version']} only; not transferred for real ({entry['level']})"
        conflicts = [f"`{p}` (shared with {', '.join(o for o in e['owners'] if o != fid)}: {e['policy']})"
                     for p, e in shared.items() if fid in e["owners"]]
        conflicts.append("a target change on the same lines as the feature is a conflict and stops this feature only")
        blocked = sorted({pattern for p in files + tests for pattern in policy["forbidden"]
                          if fnmatch.fnmatch(p, pattern)})
        non_transferable = ", ".join(f"`{p}`" for p in blocked) or "none of its files"
        if entry["level"] == "unsupported":
            non_transferable = "the whole feature (" + entry["reason"] + ")"
        limit = {"portable": "none known beyond the target contract (a Nuvio project under GPL-3.0)",
                 "adapter-required": f"needs an adapter that does not exist yet: {entry['reason']}; refused outside a trial",
                 "manual": f"manual integration only: {entry['reason']}; refused outside a trial",
                 "unsupported": f"never transferred: {entry['reason']}"}[entry["level"]]
        def listing(paths):
            return "; ".join(f"`{p}`" for p in paths) or "—"
        lines += [f"## {fid}", "",
                  f"- **Title:** {feature['title']} (since {feature['since']})",
                  f"- **Level:** {entry['level']}; verified: {'yes' if entry.get('verified') else 'no'}",
                  f"- **Supported versions:** {versions}",
                  f"- **Source sets:** {', '.join(sorted({source_set(p) for p in files + tests})) or '—'}",
                  f"- **Integration points (Nuvio files it changes):** {listing(nuvio)}",
                  f"- **Plus files:** {listing(own)}",
                  f"- **Removed upstream files:** {listing(removed)}",
                  f"- **Depends on:** {', '.join(feature.get('depends', [])) or '—'}",
                  f"- **Data formats:** {feature.get('data') or '—'}",
                  f"- **Tests:** {', '.join(feature.get('tests', [])) or '—'}; files: {listing(tests)}",
                  f"- **Not transferable:** {non_transferable}",
                  f"- **Limits:** {limit}",
                  f"- **Known conflicts:** {'; '.join(conflicts)}", ""]
    return "\n".join(lines)


def main(argv):
    text = records()
    if "--write" in argv:
        OUT.write_text(text)
        return 0
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run portkit/feature-records.py --write")
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
